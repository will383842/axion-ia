/**
 * Tests — `/[locale]/faq/par-thematique/[categorie]` : aucun gabarit
 * `{{price:…}}` ne doit sortir dans les données rendues (props FaqBlock) ni
 * dans le JSON-LD (FAQPage). Le test parcourt l'arbre React retourné.
 */
import { describe, it, expect, vi } from "vitest";

vi.mock("next-intl/server", () => ({ setRequestLocale: vi.fn() }));
vi.mock("next-intl", () => ({ hasLocale: (l: readonly string[], x: string) => l.includes(x) }));
vi.mock("next/navigation", () => ({
  notFound: () => {
    throw new Error("notFound");
  },
}));
vi.mock("@/i18n/routing", () => ({
  routing: { locales: ["fr", "en"] },
  STATIC_LOCALES: ["fr", "en"],
}));
// Composants : stubs (le test porte sur les props / données, pas sur le DOM).
vi.mock("@/components/layout/Section", () => ({ Section: () => null }));
vi.mock("@/components/layout/Container", () => ({ Container: () => null }));
vi.mock("@/components/marketing/Cta", () => ({ Cta: () => null }));
vi.mock("@/components/sections/FaqBlock", () => ({ FaqBlock: () => null }));
vi.mock("@/components/sections/CtaBlock", () => ({ CtaBlock: () => null }));
vi.mock("@/components/sections/FaqRelatedResources", () => ({ FaqRelatedResources: () => null }));
vi.mock("@/components/sections/FaqHeroImage", () => ({ FaqHeroImage: () => null }));
vi.mock("@/components/marketing/JsonLd", () => ({ JsonLd: () => null }));
vi.mock("@/components/nav/Breadcrumbs", () => ({ Breadcrumbs: () => null }));
vi.mock("@/lib/seo", () => ({
  SITE_URL: "https://axion-ia.com",
  buildProductMetadata: vi.fn(async () => ({})),
  buildItemListJsonLd: (a: unknown) => ({ itemList: a }),
  buildCollectionPageJsonLd: (a: unknown) => ({ collection: a }),
  buildPageImageGraphJsonLd: () => null,
  buildPrimaryImageOfPage: () => null,
  buildFaqJsonLd: (a: unknown) => ({ faq: a }),
}));

const GABARIT = "Le tarif est de {{price:audit-flash}} HT.";
const faq = (i: number) => ({
  slug: `q-${i}`,
  category: "general",
  isAutoGenerated: false,
  questionFr: `Question ${i} {{price:audit-flash}}`,
  questionEn: `Question ${i}`,
  answerFr: GABARIT,
  answerEn: GABARIT,
});
vi.mock("@/lib/knowledge/readers", () => ({
  listFaqs: vi.fn(async () => [1, 2, 3, 4].map(faq)),
  listFaqsByCategory: vi.fn(async () => [1, 2, 3, 4].map(faq)),
}));

import FaqCategoryPage from "./page";

describe("FAQ par thématique — jetons de prix", () => {
  it("ne laisse sortir aucun {{price: dans le rendu ni le JSON-LD", async () => {
    const tree = await FaqCategoryPage({
      params: Promise.resolve({ locale: "fr", categorie: "general" }),
    });
    const json = JSON.stringify(tree);
    expect(json).toContain("q-1");
    expect(json).not.toContain("{{price:");
    expect(json).not.toMatch(/\{\{[a-z]+:/);
    expect(json).toContain('"faq"');
  });
});
